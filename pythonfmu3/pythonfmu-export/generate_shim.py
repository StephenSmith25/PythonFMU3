"""Generate src/shim/fmi3_forwarders.cpp from src/fmi/fmi3FunctionTypes.h.

The shim is the library the importer loads on Linux/macOS. It has no link-time
dependency on libpython: on instantiation it loads libpython (unless the host process
already provides it, e.g. when the importer is itself written in Python) and then the
real implementation (the "backend" library), and forwards every FMI call to it.

Re-run this script after updating the FMI headers:
    python generate_shim.py
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
TYPES_HEADER = HERE / "src" / "fmi" / "fmi3FunctionTypes.h"
OUTPUT = HERE / "src" / "shim" / "fmi3_forwarders.cpp"

TYPEDEF_RE = re.compile(r"typedef\s+([\w\s\*]+?)\s*\b(fmi3\w+)TYPE\s*\((.*?)\)\s*;", re.S)
INSTANTIATE = {
    "fmi3InstantiateModelExchange",
    "fmi3InstantiateCoSimulation",
    "fmi3InstantiateScheduledExecution",
}


def param_names(params: str):
    params = " ".join(params.split())
    if params in ("", "void"):
        return []
    return [re.findall(r"\w+", p.replace("[]", ""))[-1] for p in params.split(",")]


def main():
    functions = [
        (" ".join(ret.split()), name, " ".join(params.split()))
        for ret, name, params in TYPEDEF_RE.findall(TYPES_HEADER.read_text())
    ]
    forwarded = [f for f in functions if f[1] != "fmi3GetVersion"]

    out = [
        "// GENERATED by generate_shim.py from fmi/fmi3FunctionTypes.h - do not edit by hand.",
        '#include "shim/shim_loader.hpp"',
        "",
        "namespace pythonfmu_shim",
        "{",
        "const char* const kFunctionNames[] = {",
        *[f'    "{name}",' for _, name, _ in forwarded],
        "};",
        f"const std::size_t kFunctionCount = {len(forwarded)};",
        "} // namespace pythonfmu_shim",
        "",
        'extern "C" {',
        "",
        "FMI3_Export const char* fmi3GetVersion(void)",
        "{",
        "    return fmi3Version;",
        "}",
        "",
    ]
    for index, (ret, name, params) in enumerate(forwarded):
        names = param_names(params)
        args = ", ".join(names)
        out.append(f"FMI3_Export {ret} {name}({params})")
        out.append("{")
        if name in INSTANTIATE:
            out.append(
                "    if (!pythonfmu_shim::ensureBackendLoaded(resourcePath, instanceEnvironment, logMessage)) return nullptr;"
            )
        out.append(f"    const auto fn = reinterpret_cast<{name}TYPE*>(pythonfmu_shim::function({index}));")
        if ret == "void":
            out.append(f"    if (fn) fn({args});")
        elif ret == "fmi3Status":
            out.append("    if (!fn) return fmi3Error;")
            out.append(f"    return fn({args});")
        else:
            out.append("    if (!fn) return nullptr;")
            out.append(f"    return fn({args});")
        out.append("}")
        out.append("")
    out.append('} // extern "C"')
    out.append("")
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(out))
    print(f"wrote {OUTPUT.relative_to(HERE)} ({len(functions)} functions)")


if __name__ == "__main__":
    main()
